"""Web packaging: the same glyphs as build/Font.ttf, split so a browser downloads only what it draws.

build/Font.ttf carries every colour format and is the file to install on a desktop (it is
about 1.5 MB, mostly the sbix bitmaps). A web page needs far less, and the formats must not
be mixed carelessly: WebKit draws a font that has COLRv1 data but no SVG table wrongly (the
overlays come out as flat squares), while it draws COLRv0 or SVG alone correctly. So the
web build is two woff2 files and a stylesheet that lets each browser choose:

  BannerFont-colrv1.woff2   COLRv1 only. Chromium and Firefox; `tech(color-COLRv1)` is true there.
  BannerFont-compat.woff2   COLRv0 + OpenType-SVG. Safari (SVG), and older Chromium/Firefox
                            (COLRv0), and any browser too old to understand `tech()`.

Browsers that do not understand `tech()` skip that source and fall through to the compat file.
"""

import io
from pathlib import Path

from fontTools.ttLib import TTFont

FAMILY = "BannerFont"
UNICODE_RANGE = "U+E000-EF42, U+F000-F07F, U+CFFF7"
COLRV1_FILE = "BannerFont-colrv1.woff2"
COMPAT_FILE = "BannerFont-compat.woff2"

CSS = f"""/* Generated by `bannerfont font`. Banner glyphs live in U+E000-EF42, the space block in
   U+F000-F07F and the negative space in U+CFFF7; the unicode-range must cover all three or
   the browser never asks this font for them. */
@font-face {{
  font-family: "{FAMILY}";
  src: url("{COLRV1_FILE}") format("woff2") tech(color-COLRv1),
       url("{COMPAT_FILE}") format("woff2");
  unicode-range: {UNICODE_RANGE};
}}
"""

# A throwaway page to open on any device or browser you want to check.
DEMO = """<!doctype html>
<meta charset="utf-8">
<title>BannerFont check</title>
<link rel="stylesheet" href="BannerFont.css">
<style>
  body { font: 16px/1.4 system-ui, sans-serif; margin: 24px; background: #4a4a6a; color: #fff; }
  .banners { font-family: "BannerFont"; font-size: 96px; line-height: 1.3; white-space: pre-wrap; }
  code { background: #0004; padding: 2px 4px; }
</style>
<h1>BannerFont check</h1>
<p>Each banner is a base followed by overlays that stack on it. Expect: a white banner with a
smooth black gradient, a teal banner with a skull, a yellow banner with bricks and a blue
triangle, a black banner with a smooth white gradient, a red banner with a skull. A flat
square where a skull should be, or hard bands in the gradient, means a fallback is in use.</p>
<div class="banners">&#xE000;&#xE313;&#xE00C;&#xEB00;&#xE722;&#xE00C;&#xE000;&#xE402;&#xEA37;&#xE00C;&#xE300;&#xE014;&#xE00C;&#xE600;&#xE613;&#xE122;</div>
<h2>Every colour, plain base</h2>
<div class="banners">&#xE000;&#xE100;&#xE200;&#xE300;&#xE400;&#xE500;&#xE600;&#xE700;&#xE800;&#xE900;&#xEA00;&#xEB00;&#xEC00;&#xED00;&#xEE00;&#xEF00;</div>
<h2>Browser support</h2>
<pre id="support"></pre>
<script>
  const techs = ["color-COLRv1", "color-COLRv0", "color-SVG", "color-sbix", "color-CBDT"];
  document.getElementById("support").textContent = techs
    .map((t) => t + ": " + CSS.supports("font-tech(" + t + ")")).join("\\n");
</script>
"""


def woff2_bytes(ttf: bytes) -> bytes:
    font = TTFont(io.BytesIO(ttf))
    font.flavor = "woff2"
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def write(web_dir: Path, build) -> dict[str, int]:
    """Write the woff2 files, the stylesheet and the check page. `build(formats)` returns TTF bytes.
    Returns file name -> size in bytes, for the build log."""
    web_dir.mkdir(parents=True, exist_ok=True)
    files = {
        COLRV1_FILE: woff2_bytes(build(("colrv1",))),
        COMPAT_FILE: woff2_bytes(build(("colrv0", "svg"))),
    }
    for name, data in files.items():
        (web_dir / name).write_bytes(data)
    (web_dir / "BannerFont.css").write_text(CSS)
    (web_dir / "index.html").write_text(DEMO)
    return {name: len(data) for name, data in files.items()}
